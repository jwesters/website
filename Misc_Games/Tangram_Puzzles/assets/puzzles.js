  const rotatePuzzle = (baseIndex, name, degrees, difficulty = "Hard") => {
    const base = window.TANGRAM_PUZZLES[baseIndex];
    const r = degrees * Math.PI / 180;
    const rot = ([x,y]) => [
      +(x*Math.cos(r) - y*Math.sin(r)).toFixed(4),
      +(x*Math.sin(r) + y*Math.cos(r)).toFixed(4)
    ];
    const pieces = base.pieces.map(q => {
      const [x,y] = rot([q.x,q.y]);
      return s(q.source, x, y, (q.a + degrees + 360) % 360, q.f);
    });
    const outline = base.outline.map(loop => loop.map(rot));
    window.TANGRAM_PUZZLES.push(p(name, difficulty, pieces, outline));
  };

